// Original centre-line guides, independent of fonts. Educational review is pending.
StrokePath _line(List<double> coordinates) => StrokePath([
  for (var i = 0; i < coordinates.length; i += 2)
    TracePoint(coordinates[i], coordinates[i + 1]),
]);

StrokePath _oval(
  double x,
  double y,
  double rx,
  double ry, {
  double start = -math.pi / 2,
  double sweep = -2 * math.pi,
}) => StrokePath([
  for (var i = 0; i <= 48; i++)
    TracePoint(
      x + rx * math.cos(start + sweep * i / 48),
      y + ry * math.sin(start + sweep * i / 48),
    ),
]);

List<StrokePath> _fit(
  List<StrokePath> paths,
  double x,
  double y,
  double width,
  double height,
) => paths
    .map(
      (path) => StrokePath([
        for (final point in path.points)
          TracePoint(x + point.x * width, y + point.y * height),
      ]),
    )
    .toList();

