StoryEpisode retellChapter(StoryEpisode source) {
  final direction = chapterDirections[source.id - 1];
  const suffixes = [
    'start',
    'discover',
    'choice',
    'quiz',
    'clue',
    'trace',
    'review',
    'talk',
    'together',
    'end',
  ];
  return StoryEpisode(
    id: source.id,
    title: source.title,
    goal: direction.goal,
    reward: '책등 조각 ${source.id}',
    scenes: [
      for (final scene in source.scenes)
        scene.reword(
          text: direction.pages[suffixes.indexOf(scene.id.split('-').last)],
          success:
              scene.interaction == StoryPhase.quiz ||
                  scene.interaction == StoryPhase.tracing
              ? scene.interaction == StoryPhase.tracing
                    ? '모양을 끝까지 이었어요. 조각으로 가는 길이 이어져요.'
                    : scene.id.endsWith('-quiz')
                    ? '맞는 표지를 찾았어요. 조각을 꺼낼 준비가 한 걸음 진행됐어요.'
                    : scene.id.endsWith('-review')
                    ? '길의 표지를 확인했어요. 빠뜨린 곳을 하나 더 고쳤어요.'
                    : '마지막 준비를 함께 마쳤어요.'
              : null,
          explore: scene.exploreText == null
              ? null
              : '친구가 이 길을 고치려 해요.\n마음에 드는 그림을 누르면 함께 도와줄 거예요.',
          exploreSuccess: scene.exploreQuiz == null
              ? null
              : '예쁜 빛을 골랐어요! 친구가 길을 고쳐 주었어요.',
        ),
    ],
  );
}
